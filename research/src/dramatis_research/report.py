"""Render evaluation results as markdown. Sets are separate sections; nothing is pooled."""

from __future__ import annotations

import json
from pathlib import Path

SET_TITLES = {
    "structural": "Held-out structural set",
    "synthetic": "Held-out synthetic set",
    "verify": "Verify set",
}


def _f(v, pct: bool = False) -> str:
    if v is None:
        return "n/a"
    return f"{v * 100:.1f}%" if pct else f"{v:.3f}"


def _cost(c: dict) -> tuple[str, str]:
    calls = c["llm_calls_for_data"]
    return ("unknown" if calls is None else str(calls)), f"{c['gpu_hours']:.2f}"


def render(results: dict) -> str:
    meta = results["meta"]
    out = [
        "# Research results",
        "",
        "Generated by `dramatis-research evaluate`. Do not edit.",
        "",
        f"- pool: {meta['pool']} ({meta['pool_size']} items)",
        f"- rerank depth: {meta['rerank_depth']}; query cap per set: {meta['max_queries'] or 'none'}",
        "- each set below is scored separately; there is no combined score",
        "",
    ]
    floor = meta["lexical_floor"]
    for name, block in results["sets"].items():
        systems = block["systems"]
        out += [f"## {SET_TITLES.get(name, name)}", "", f"{block['queries']} queries.", ""]
        out += [
            "Macro average over families (equal weight per family).",
            "",
            "| system | nDCG@10 | recall@10 | recall@50 | MRR | negative win rate "
            "| LLM calls (data) | GPU hours |",
            "| --- | --- | --- | --- | --- | --- | --- | --- |",
        ]
        for sys_name, r in systems.items():
            m = r["macro"]
            cost = results["systems"].get(sys_name, {}).get("cost")
            calls, gpu = _cost(cost) if cost else ("-", "-")
            out.append(
                f"| {sys_name} | {_f(m.get('ndcg@10'))} | {_f(m.get('recall@10'))} "
                f"| {_f(m.get('recall@50'))} | {_f(m.get('mrr'))} "
                f"| {_f(m.get('negwin'), pct=True)} | {calls} | {gpu} |"
            )
        out.append("")

        lexical = systems.get("bm25", {}).get("by_family", {})
        names = list(systems)
        for metric, title, pct in (
            ("ndcg@10", "nDCG@10", False),
            ("negwin", "negative win rate", True),
        ):
            out += [
                f"### {title} per family",
                "",
                "| family | queries | " + " | ".join(names) + " |",
            ]
            out.append("| --- | --- | " + " | ".join("---" for _ in names) + " |")
            for fam in block["families"]:
                mark = ""
                if lexical.get(fam, {}).get("ndcg@10", 0.0) >= floor:
                    mark = " *"
                n = lexical.get(fam, {}).get("queries", 0)
                cells = [_f(systems[s]["by_family"].get(fam, {}).get(metric), pct) for s in names]
                out.append(f"| {fam}{mark} | {n} | " + " | ".join(cells) + " |")
            out.append("")
        out += [
            f"`*` lexical floor: BM25 alone reaches nDCG@10 >= {floor} on this family. Such a "
            "family is a sanity check on the pipeline, not evidence of retrieval quality.",
            "",
        ]
    out += [
        "Notes:",
        "- `bm25` is a BM25 over the exported pool; `bm25-engine` (structural set only) is the "
        "engine's lexical evaluation over its full index and is not a peer row.",
        "- Cost columns: LLM calls spent producing the training data, and accelerator hours of "
        "the training run(s) behind the system. Base systems cost nothing.",
        "",
    ]
    return "\n".join(out)


def write(results: dict, directory: Path, stem: str = "RESULTS-research") -> tuple[Path, Path]:
    directory.mkdir(parents=True, exist_ok=True)
    md = directory / f"{stem}.md"
    js = directory / f"{stem}.json"
    md.write_text(render(results))
    js.write_text(json.dumps(results, indent=2, sort_keys=True) + "\n")
    return md, js
